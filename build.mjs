import {mkdir,writeFile,readFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import foundations from './source/01-foundations.mjs';
import navigation from './source/02-navigation.mjs';
import inputs from './source/03-inputs.mjs';
import people from './source/04-people.mjs';
import projects from './source/05-projects.mjs';
import data from './source/06-data.mjs';
import time from './source/07-time.mjs';
import messages from './source/08-messages.mjs';
import media from './source/09-media.mjs';
import play from './source/10-play.mjs';
const directory=fileURLToPath(new URL('.',import.meta.url));
const categories=[
  ['Foundations','The familiar, with a little feeling.',foundations,'#f0a4bf'],
  ['Navigation','Taking the scenic route without getting lost.',navigation,'#b9cd99'],
  ['Inputs','A more human way to put a thought in.',inputs,'#9dc8e3'],
  ['People','The humans behind the little good things.',people,'#f4cd50'],
  ['Projects','Make the unfinished feel full of possibility.',projects,'#ed9b6d'],
  ['Data','Numbers that tell a story you can feel.',data,'#b9cd99'],
  ['Time','A little room for focus, rest, and someday.',time,'#f4cd50'],
  ['Messages','Kind words, clear choices, and second chances.',messages,'#f0a4bf'],
  ['Media','Play, frame, annotate, and keep a moment.',media,'#9dc8e3'],
  ['Play','Useful little experiments at the edge of UI.',play,'#ed9b6d']
];
const escape=value=>String(value).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const all=categories.flatMap(([category,subtitle,components,color],categoryIndex)=>components.map((component,index)=>({...component,category,subtitle,color,number:categoryIndex*10+index+1})));
if(all.length!==100)throw new Error('Expected exactly 100 components.');
for(const key of ['slug','title','html','js'])if(new Set(all.map(c=>c[key])).size!==100)throw new Error('Duplicate '+key+' in collection.');
for(const item of all)new Function(item.js); // Validate every script before writing the collection.
await mkdir(directory+'components',{recursive:true});
const catalog=[];
for(const item of all){
  const number=String(item.number).padStart(3,'0');
  const filename=number+'-'+item.slug+'.html';
  const html=`<!doctype html>
<!-- Generated by build.mjs. Edit source/${String(Math.ceil(item.number/10)).padStart(2,'0')}-*.mjs instead. -->
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="description" content="${escape(item.description)}"><title>${escape(item.title)} / Little UI, Big Feelings</title><link rel="icon" href="../assets/favicon.svg" type="image/svg+xml"><link rel="stylesheet" href="../assets/paper.css"><script>const params=new URLSearchParams(location.search);if(params.has('preview'))document.documentElement.classList.add('preview');if(params.has('thumbnail'))document.documentElement.classList.add('thumbnail');</script><style>body{--accent:${item.color}}${item.css}</style></head>
<body class="component-page"><header class="component-header"><a href="../index.html">← Back to the scrapbook</a><span class="eyebrow">${escape(item.category)} / A little UI experiment</span></header><div class="component-intro"><div><h1>${escape(item.title)}</h1><p>${escape(item.description)}</p></div><span class="component-number">${number}</span></div><main class="demo-stage"><div class="demo">${item.html}</div></main><footer class="component-footer"><span class="hand">give it a try →</span>${escape(item.hint)}</footer><div id="live-status" class="live-status" role="status" aria-live="polite" hidden></div><script src="../assets/runtime.js"></script><script>(function(){'use strict';${item.js}\n})();document.documentElement.dataset.experimentReady='true';</script></body></html>\n`;
  await writeFile(directory+'components/'+filename,html);
  catalog.push({number:item.number,slug:item.slug,title:item.title,description:item.description,hint:item.hint,category:item.category,color:item.color,file:'components/'+filename,source:html});
}
await writeFile(directory+'assets/catalog.js','/* Generated by build.mjs. Edit source modules instead. */\nwindow.SCRAPBOOK_CATEGORIES='+JSON.stringify(categories.map(([name,subtitle,,color])=>({name,subtitle,color})))+';\nwindow.SCRAPBOOK_COMPONENTS='+JSON.stringify(catalog)+';\n');
await readFile(directory+'index.html');
console.log('Built 100 unique HTML experiments across 10 categories. Gallery: index.html');
